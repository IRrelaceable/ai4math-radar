export function archiveYears(records: LabArchiveRecord[] = LAB_ARCHIVE): string[] {
  return [...new Set(records.map((r) => r.date.slice(0, 4)))].sort().reverse();
}

export function archiveByYear(records: LabArchiveRecord[] = LAB_ARCHIVE): { year: string; records: LabArchiveRecord[] }[] {
  return archiveYears(records).map((year) => ({
    year,
    records: records
      .filter((r) => r.date.startsWith(year))
      .sort((a, b) => b.date.localeCompare(a.date) || a.n - b.n),
  }));
}

