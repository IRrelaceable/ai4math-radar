import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadEnv } from "./env";
import { events as seedEvents } from "@/data/seed/events";
import { readIngestedEvents, INGESTED_FILE } from "@/lib/db/ingested";
import { classifyDirection, isDirectionEligible } from "@/agents/researchTracker/direction";
import { getLLMProvider } from "@/lib/llm/provider";
import type { EventDirection, ResearchEvent } from "@/types";

/**
 * Assign the direction axis (ai4math / math4ai / both) to every research
 * event, under the fixed rubric in agents/researchTracker/direction.ts.
 *
 * Curated prose lives in TypeScript, so seed events get a generated
 * slug-keyed overlay (`data/seed/directions.ts`) applied by the seed
 * assembly; stored events are written directly into `data/ingested/events.json`.
 * Ecosystem events are skipped — no researchArea, same rule as the area axis.
 *
 *   npm run backfill:direction               # missing entries only
 *   npm run backfill:direction -- --dry
 *   npm run backfill:direction -- --force    # redo every entry
 *   npm run backfill:direction -- --limit=5 --only=a,b
 */
const CONCURRENCY = 4;
const MAX_ATTEMPTS = 3;
const OUT = path.join(process.cwd(), "data", "seed", "directions.ts");

function parseArgs() {
  const argv = process.argv.slice(2);
  const limitArg = argv.find((value) => value.startsWith("--limit="));
  const limit = limitArg ? Number(limitArg.slice("--limit=".length)) : undefined;
  const onlyArg = argv.find((value) => value.startsWith("--only="));
  return {
    dry: argv.includes("--dry"),
    force: argv.includes("--force"),
    limit: Number.isInteger(limit) && (limit ?? 0) > 0 ? limit : undefined,
    only: onlyArg ? new Set(onlyArg.slice("--only=".length).split(",").filter(Boolean)) : undefined,
  };
}

async function loadExisting(): Promise<Record<string, EventDirection>> {
  if (!fs.existsSync(OUT)) return {};
  try {
    const module = (await import(pathToFileURL(OUT).href)) as {
      DIRECTIONS?: Record<string, EventDirection>;
    };
    return module.DIRECTIONS ?? {};
  } catch (error) {
    console.warn("existing overlay unreadable, starting over:", String(error).slice(0, 160));
    return {};
  }
}

function render(record: Record<string, EventDirection>): string {
  const sorted = Object.fromEntries(
    Object.keys(record)
      .sort()
      .map((slug) => [slug, record[slug]])
  );
  const json = JSON.stringify(sorted, null, 2).replace(/\n/g, "\n  ");
  return (
    "/* eslint-disable */\n" +
    "// Generated by scripts/backfill-direction.ts — do not edit by hand.\n" +
    'import type { EventDirection } from "../../types";\n\n' +
    "/** Direction axis for curated events, keyed by slug. */\n" +
    `export const DIRECTIONS: Record<string, EventDirection> = ${json};\n`
  );
}

type Job =
  | { kind: "seed"; slug: string; event: ResearchEvent }
  | { kind: "ingested"; index: number; event: ResearchEvent };

async function main() {
  loadEnv();
  const { dry, force, limit, only } = parseArgs();

  const provider = getLLMProvider();
  if (provider.id === "mock") {
    throw new Error("direction backfill needs a live provider; set LLM_PROVIDER=openai-compatible in .env");
  }

  const existing = force && !only ? {} : await loadExisting();
  const ingested = readIngestedEvents();
  const eligible = (event: ResearchEvent, hasEntry: boolean) =>
    isDirectionEligible(event) &&
    (force || !hasEntry) &&
    (!only || only.has(event.slug));

  const queue: Job[] = [
    ...seedEvents
      .filter((event) => eligible(event, Boolean(existing[event.slug])))
      .map((event) => ({ kind: "seed" as const, slug: event.slug, event })),
    ...ingested
      .map((event, index) => ({ event, index }))
      .filter(({ event }) => eligible(event, Boolean(event.direction)))
      .map(({ event, index }) => ({ kind: "ingested" as const, index, event })),
  ].slice(0, limit ?? Number.MAX_SAFE_INTEGER);

  const ecosystem = seedEvents.filter((event) => !isDirectionEligible(event)).length +
    ingested.filter((event) => !isDirectionEligible(event)).length;
  console.log(
    `direction backfill: ${queue.length} eligible events ` +
      `(${Object.keys(existing).length} seed entries already stored, ` +
      `${ingested.filter((e) => e.direction).length} stored; ${ecosystem} ecosystem events skipped)`
  );

  if (dry) {
    for (const job of queue) console.log("  would classify:", job.event.slug);
    return;
  }

  let ingestedDirty = false;
  const writeOverlay = () => fs.writeFileSync(OUT, render(existing), "utf8");
  const writeIngested = () => {
    if (!ingestedDirty) return;
    fs.writeFileSync(INGESTED_FILE, JSON.stringify(ingested, null, 2), "utf8");
  };

  const counts: Record<string, number> = {};
  const total = queue.length;
  let done = 0;
  let failed = 0;

  async function worker(): Promise<void> {
    for (;;) {
      const job = queue.shift();
      if (!job) return;
      // Transient provider errors surface as "no answer"; retry with backoff
      // before giving up, so one 429 does not silently drop an event.
      let direction = await classifyDirection(job.event, provider);
      for (let attempt = 1; !direction && attempt < MAX_ATTEMPTS; attempt++) {
        await new Promise((resolve) => setTimeout(resolve, 2_000 * attempt));
        direction = await classifyDirection(job.event, provider);
      }
      done += 1;
      if (!direction) {
        failed += 1;
        console.log(`[${done}/${total}] no answer after ${MAX_ATTEMPTS} attempts: ${job.event.slug}`);
        continue;
      }
      counts[direction] = (counts[direction] ?? 0) + 1;
      if (job.kind === "seed") {
        existing[job.slug] = direction;
        writeOverlay();
      } else {
        ingested[job.index] = { ...job.event, direction };
        ingestedDirty = true;
        writeIngested();
      }
      console.log(`[${done}/${total}] ${job.event.slug} -> ${direction}`);
      if (done % 10 === 0) console.log(`progress ${done}/${total}`, counts);
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  writeOverlay();
  writeIngested();
  console.log(
    `\nDone: ${done - failed}/${done} classified`, counts,
    failed > 0 ? `(${failed} failed — re-run without --force to retry just those)` : ""
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
