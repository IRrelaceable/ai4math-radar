import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import type { AiRoleLevel } from "@/types";
import { events } from "@/data/seed/events";
import { extractContribution } from "@/agents/researchTracker/contribution";
import { loadEnv } from "./env";

/**
 * Give curated seed events their AI role and human contribution.
 *
 * Curated prose lives in TypeScript sources, so the ingest pipeline can never
 * touch it. This writes a generated slug-keyed overlay instead
 * (`data/seed/ai-roles.ts`); the seed assembly applies it to events that do not
 * declare a role themselves. The stored summary is the only source text the
 * extractor sees, so it can only restate what the curated entry already says.
 *
 *   npx tsx scripts/backfill-curated-ai-role.ts [--dry] [--force] [--limit=5] [--only=a,b]
 */
const CONCURRENCY = 4;
const OUT = path.join(process.cwd(), "data", "seed", "ai-roles.ts");

interface CuratedAiRole {
  level: AiRoleLevel;
  description?: string;
  humanContribution?: string;
  zh?: { description?: string; humanContribution?: string };
}

function parseLimit(): number | undefined {
  const arg = process.argv.find((value) => value.startsWith("--limit="));
  if (!arg) return undefined;
  const limit = Number(arg.slice("--limit=".length));
  return Number.isInteger(limit) && limit > 0 ? limit : undefined;
}

function parseOnly(): Set<string> | undefined {
  const arg = process.argv.find((value) => value.startsWith("--only="));
  if (!arg) return undefined;
  return new Set(arg.slice("--only=".length).split(",").filter(Boolean));
}

async function loadExisting(): Promise<Record<string, CuratedAiRole>> {
  if (!fs.existsSync(OUT)) return {};
  try {
    const module = (await import(pathToFileURL(OUT).href)) as {
      CURATED_AI_ROLES?: Record<string, CuratedAiRole>;
    };
    return module.CURATED_AI_ROLES ?? {};
  } catch (error) {
    // A half-written or broken overlay must not block the run: regenerate it.
    console.warn("existing overlay unreadable, starting over:", String(error).slice(0, 160));
    return {};
  }
}

function render(record: Record<string, CuratedAiRole>): string {
  const sorted = Object.fromEntries(
    Object.keys(record)
      .sort()
      .map((slug) => [slug, record[slug]])
  );
  const json = JSON.stringify(sorted, null, 2).replace(/\n/g, "\n  ");
  return (
    "/* eslint-disable */\n" +
    "// Generated by scripts/backfill-curated-ai-role.ts — do not edit by hand.\n" +
    "import type { AiRoleLevel } from \"../../types\";\n\n" +
    "export interface CuratedAiRole {\n" +
    "  level: AiRoleLevel;\n" +
    "  description?: string;\n" +
    "  humanContribution?: string;\n" +
    "  zh?: { description?: string; humanContribution?: string };\n" +
    "}\n\n" +
    "/** AI attribution for curated events, keyed by slug. */\n" +
    `export const CURATED_AI_ROLES: Record<string, CuratedAiRole> = ${json};\n`
  );
}

async function main() {
  loadEnv();
  const dry = process.argv.includes("--dry");
  const force = process.argv.includes("--force");
  const limit = parseLimit();
  const only = parseOnly();
  // A forced re-run re-derives every level, so entries that the extractor now
  // rejects must not survive from the previous pass. A targeted retry keeps the
  // other entries and only re-derives the named slugs.
  const existing = force && !only ? {} : await loadExisting();

  const research = events.filter((event) => event.eventType === "Research");
  const targets = research
    .filter((event) => force || (!event.aiRole && !existing[event.slug]))
    .filter((event) => !only || only.has(event.slug))
    .slice(0, limit ?? Number.MAX_SAFE_INTEGER);
  console.log(
    `${targets.length} of ${research.length} curated Research events need AI attribution ` +
      `(${Object.keys(existing).length} already stored)`
  );

  if (dry) {
    console.log("dry run — nothing requested, nothing written");
    const byYear: Record<string, number> = {};
    for (const event of targets) byYear[event.date.slice(0, 4)] = (byYear[event.date.slice(0, 4)] ?? 0) + 1;
    console.log("by year:", byYear);
    for (const event of targets) console.log("  would process:", event.date, event.slug);
    return;
  }

  const write = () => fs.writeFileSync(OUT, render(existing), "utf8");

  const levels: Record<string, number> = {};
  let enOnly = 0;
  let processed = 0;
  const queue = [...targets];

  async function worker(): Promise<void> {
    for (;;) {
      const event = queue.shift();
      if (!event) return;
      processed += 1;
      try {
        const contribution = event.summary?.trim()
          ? await extractContribution({
              title: event.title,
              abstract: event.summary,
              source: event.sourceUrl,
            })
          : undefined;
        if (!contribution) {
          levels.failed = (levels.failed ?? 0) + 1;
          console.log("no attribution:", event.slug);
        } else if (contribution.en.level === "not_applicable") {
          levels.not_applicable = (levels.not_applicable ?? 0) + 1;
          if (existing[event.slug]) {
            delete existing[event.slug];
            write();
          }
        } else {
          const { level, description, humanContribution } = contribution.en;
          existing[event.slug] = {
            level,
            ...(description ? { description } : {}),
            ...(humanContribution ? { humanContribution } : {}),
            ...(contribution.zh?.description || contribution.zh?.humanContribution
              ? {
                  zh: {
                    ...(contribution.zh.description ? { description: contribution.zh.description } : {}),
                    ...(contribution.zh.humanContribution
                      ? { humanContribution: contribution.zh.humanContribution }
                      : {}),
                  },
                }
              : {}),
          };
          levels[level] = (levels[level] ?? 0) + 1;
          if (description && !contribution.zh?.description) {
            enOnly += 1;
            console.log("missing zh attribution:", event.slug);
          }
          write();
        }
      } catch (error) {
        levels.failed = (levels.failed ?? 0) + 1;
        console.log("failed:", event.slug, String(error).slice(0, 160));
      }
      if (processed % 10 === 0) console.log(`progress ${processed}/${targets.length}`, levels);
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  write();
  console.log("done", levels, "en-only", enOnly, "stored", Object.keys(existing).length);
}

main();
