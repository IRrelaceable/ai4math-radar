import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { readIngestedEvents, INGESTED_FILE } from "@/lib/db/ingested";
import type { EventDirection, ResearchEvent } from "@/types";

/**
 * Apply confirmed rows from the direction audit cache.
 *
 *   npm run apply:direction -- --only=slug-a,slug-b --dry
 *   npm run apply:direction -- --only=slug-a,slug-b
 *   npm run apply:direction -- --all-changed --min-confidence=0.8
 *   npm run apply:direction -- --labels=docs/confirmed-labels.json --dry
 *
 * There is deliberately no default: a run must name slugs, opt into
 * `--all-changed`, or supply a reviewed label file, so a routine invocation
 * cannot overwrite the whole dataset. Seed events store the axis in the
 * generated overlay; ingested events store it on the event itself. A `none`
 * verdict removes the stored axis.
 */

const CACHE_FILE = path.join(process.cwd(), ".cache", "direction-audit.json");
const SEED_OVERLAY = path.join(process.cwd(), "data", "seed", "directions.ts");

interface AuditRow {
  slug: string;
  title: string;
  source: "seed" | "ingested";
  oldDirection?: EventDirection;
  analysis?: {
    verdict: EventDirection | "none";
    confidence: number;
  };
}

function parseArgs() {
  const argv = process.argv.slice(2);
  const onlyArg = argv.find((value) => value.startsWith("--only="));
  const confidenceArg = argv.find((value) => value.startsWith("--min-confidence="));
  const labelsArg = argv.find((value) => value.startsWith("--labels="));
  const minConfidence = confidenceArg
    ? Number(confidenceArg.slice("--min-confidence=".length))
    : undefined;
  return {
    dry: argv.includes("--dry"),
    allChanged: argv.includes("--all-changed"),
    only: onlyArg
      ? new Set(onlyArg.slice("--only=".length).split(",").filter(Boolean))
      : undefined,
    labelsPath: labelsArg ? labelsArg.slice("--labels=".length) : undefined,
    minConfidence:
      Number.isFinite(minConfidence) && (minConfidence ?? 0) >= 0
        ? minConfidence
        : undefined,
  };
}

const DIRECTIONS = new Set(["ai4math", "math4ai", "both", "none"]);

/** Read a human-confirmed `slug -> direction` map into cache-shaped rows. */
async function readLabelRows(file: string): Promise<AuditRow[]> {
  const full = path.resolve(process.cwd(), file);
  if (!fs.existsSync(full)) throw new Error(`label file not found: ${full}`);
  const labels = JSON.parse(fs.readFileSync(full, "utf8")) as Record<string, string>;
  const ingested = readIngestedEvents();
  const index = new Map(ingested.map((event) => [event.slug, event]));
  const overlay = await loadOverlay();
  return Object.entries(labels).map(([slug, verdict]) => {
    if (!DIRECTIONS.has(verdict)) {
      throw new Error(`invalid direction for ${slug}: ${verdict}`);
    }
    const event = index.get(slug);
    return {
      slug,
      title: event?.title ?? slug,
      source: event ? "ingested" : "seed",
      oldDirection: (event?.direction ?? overlay[slug]) as EventDirection | undefined,
      analysis: { verdict: verdict as EventDirection | "none", confidence: 1 },
    };
  });
}

function readCache(): Record<string, AuditRow> {
  if (!fs.existsSync(CACHE_FILE)) {
    throw new Error(`audit cache not found: ${CACHE_FILE}\nRun npm run audit:direction first.`);
  }
  return JSON.parse(fs.readFileSync(CACHE_FILE, "utf8")) as Record<string, AuditRow>;
}

async function loadOverlay(): Promise<Record<string, EventDirection>> {
  if (!fs.existsSync(SEED_OVERLAY)) return {};
  const module = (await import(pathToFileURL(SEED_OVERLAY).href)) as {
    DIRECTIONS?: Record<string, EventDirection>;
  };
  return { ...(module.DIRECTIONS ?? {}) };
}

function renderOverlay(record: Record<string, EventDirection>): string {
  const sorted = Object.fromEntries(
    Object.keys(record)
      .sort()
      .map((slug) => [slug, record[slug]])
  );
  const json = JSON.stringify(sorted, null, 2).replace(/\n/g, "\n  ");
  return (
    "/* eslint-disable */\n" +
    "// Generated by scripts/backfill-direction.ts — do not edit by hand.\n" +
    'import type { EventDirection } from "../../types";\n\n' +
    "/** Direction axis for curated events, keyed by slug. */\n" +
    `export const DIRECTIONS: Record<string, EventDirection> = ${json};\n`
  );
}

function selectRows(rows: AuditRow[], only: Set<string> | undefined, allChanged: boolean): AuditRow[] {
  if (!only && !allChanged) {
    throw new Error("Refusing to write without a selection: pass --only=slug-a,slug-b or --all-changed.");
  }
  const judged = rows.filter((row) => row.analysis);
  if (only) {
    const missing = [...only].filter((slug) => !judged.some((row) => row.slug === slug));
    if (missing.length > 0) {
      throw new Error(`No audit result for: ${missing.join(", ")}. Run the audit first.`);
    }
    return judged.filter((row) => only.has(row.slug));
  }
  return judged.filter((row) => row.analysis!.verdict !== row.oldDirection);
}

async function main(): Promise<void> {
  const { dry, only, allChanged, minConfidence, labelsPath } = parseArgs();
  const cache = readCache();
  const rows = labelsPath ? await readLabelRows(labelsPath) : Object.values(cache);
  const selected = (labelsPath ? rows : selectRows(rows, only, allChanged)).filter((row) => {
    if (minConfidence === undefined) return true;
    return (row.analysis?.confidence ?? 0) >= minConfidence;
  });

  if (selected.length === 0) {
    console.log("Nothing selected.");
    return;
  }

  const skipped = selected.filter(
    (row) => row.analysis!.verdict === row.oldDirection
  );
  const changes = selected.filter(
    (row) => row.analysis!.verdict !== row.oldDirection
  );

  console.log(`selected ${selected.length}, changing ${changes.length}, no-op ${skipped.length}`);
  for (const row of changes) {
    console.log(
      `  ${row.source === "seed" ? "seed" : "ingested"} ${row.slug}: ` +
        `${row.oldDirection ?? "none"} -> ${row.analysis!.verdict} ` +
        `(${row.analysis!.confidence.toFixed(2)})`
    );
  }

  if (dry) {
    console.log("\n--dry: no files written.");
    return;
  }

  const overlay = await loadOverlay();
  const ingested: ResearchEvent[] = readIngestedEvents();
  const ingestedIndex = new Map(ingested.map((event, index) => [event.slug, index]));
  let overlayDirty = false;
  let ingestedDirty = false;

  for (const row of changes) {
    const verdict = row.analysis!.verdict;
    if (row.source === "seed") {
      if (verdict === "none") {
        delete overlay[row.slug];
      } else {
        overlay[row.slug] = verdict;
      }
      overlayDirty = true;
      continue;
    }

    const index = ingestedIndex.get(row.slug);
    if (index === undefined) {
      console.warn(`ingested event disappeared, skipped: ${row.slug}`);
      continue;
    }
    const event = ingested[index];
    if (verdict === "none") {
      const { direction: _direction, ...rest } = event;
      ingested[index] = rest as ResearchEvent;
    } else {
      ingested[index] = { ...event, direction: verdict };
    }
    ingestedDirty = true;
  }

  if (overlayDirty) fs.writeFileSync(SEED_OVERLAY, renderOverlay(overlay), "utf8");
  if (ingestedDirty) fs.writeFileSync(INGESTED_FILE, JSON.stringify(ingested, null, 2), "utf8");
  console.log(`\nWrote ${overlayDirty ? SEED_OVERLAY + " " : ""}${ingestedDirty ? INGESTED_FILE : ""}`.trim());
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
